#!/usr/bin/env node
// 실제 Electron·IPC·stdio 검증이며 Native는 합성 fixture다.
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import { createServer } from "node:net";
import path from "node:path";
import { fileURLToPath } from "node:url";

type Data = Record<string, unknown>;
const obj = (value: unknown): Data => value && typeof value === "object" && !Array.isArray(value) ? value as Data : {};
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const evidence = await fs.mkdtemp(path.join(root, ".www/evidence/sessions-ui-"));
const workspace = path.join(evidence, "workspace");
await fs.mkdir(workspace);
const checks: string[] = [];
const pause = (ms: number) => new Promise<void>(resolve => setTimeout(resolve, ms));
const server = createServer();
await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
const address = server.address();
if (!address || typeof address === "string") throw Error("포트 없음");
const port = address.port;
await new Promise<void>(resolve => server.close(() => resolve()));
const stdout = await fs.open(path.join(evidence, "electron.stdout"), "w");
const stderr = await fs.open(path.join(evidence, "electron.stderr"), "w");
const env: NodeJS.ProcessEnv = { ...process.env, WWW_PROBE_PATH: path.join(evidence, "disabled.json"), WWW_NATIVE_PROBE: "1", WWW_PROBE_WORKSPACE: workspace, WWW_CODEX_BIN: path.join(root, "test/fixtures/sessions-app-server.ts"), WWW_PROBE_NATIVE_REPORTS: "0", WWW_SESSION_FIXTURE_DIR: evidence };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(path.join(root, "node_modules/electron/dist/Electron.app/Contents/MacOS/Electron"), [root, `--remote-debugging-port=${port}`, `--user-data-dir=${path.join(evidence, "profile")}`], { cwd: root, env, stdio: ["ignore", stdout.fd, stderr.fd] });
let socket: WebSocket | null = null;
try {
  let endpoint = "";
  for (let i = 0; i < 400 && !endpoint; i++) {
    if (child.exitCode !== null) throw Error(`Electron 조기 종료: ${child.exitCode}`);
    try { const targets: unknown = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json(); if (Array.isArray(targets)) endpoint = String(obj(targets.find(value => obj(value).type === "page")).webSocketDebuggerUrl ?? ""); } catch {}
    if (!endpoint) await pause(50);
  }
  if (!endpoint) throw Error("CDP 연결 실패");
  socket = new WebSocket(endpoint);
  await new Promise<void>((resolve, reject) => { socket!.addEventListener("open", () => resolve(), { once: true }); socket!.addEventListener("error", () => reject(Error("CDP 연결 오류")), { once: true }); });
  let nextId = 0;
  const pending = new Map<number, { resolve(value: unknown): void; reject(error: Error): void }>();
  socket.addEventListener("message", event => { const message = obj(JSON.parse(String(event.data))); if (typeof message.id !== "number") return; const waiter = pending.get(message.id); if (!waiter) return; pending.delete(message.id); if (message.error) waiter.reject(Error(JSON.stringify(message.error))); else waiter.resolve(message.result); });
  const command = (method: string, params: Data = {}): Promise<unknown> => new Promise((resolve, reject) => { const id = ++nextId; pending.set(id, { resolve, reject }); socket!.send(JSON.stringify({ id, method, params })); });
  const evaluate = async (expression: string) => { const value = obj(await command("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true, userGesture: true })); if (value.exceptionDetails) throw Error(JSON.stringify(value.exceptionDetails)); return obj(value.result).value; };
  const wait = async (expression: string, label: string) => { for (let i = 0; i < 400; i++) { if (await evaluate(`(async()=>Boolean(await (${expression})))()`)) { checks.push(label); return; } await pause(50); } throw Error(`${label}: ${String(await evaluate("document.body.innerText"))}`); };
  const click = async (selector: string) => { await evaluate(`(()=>{const n=document.querySelector(${JSON.stringify(selector)});if(!(n instanceof HTMLElement)||n.closest('[hidden]')||('disabled' in n&&n.disabled))throw Error('클릭 불가: '+${JSON.stringify(selector)});n.click()})()`); };
  const input = async (id: string, value: string) => { await evaluate(`(()=>{const n=document.querySelector(${JSON.stringify(`[data-session-id="${id}"] [data-testid="prompt-input"]`)});Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(n,${JSON.stringify(value)});n.dispatchEvent(new Event('input',{bubbles:true}))})()`); };
  const surface = (id: string) => `[data-session-id="${id}"]`;
  const tab = (id: string) => `[id="session-tab-${id}"]`;
  const select = async (id: string) => { await click(tab(id)); await wait(`document.querySelector(${JSON.stringify(surface(id))})?.hidden===false`, `탭 ${id} 활성화`); };
  const chat = async (id: string) => {
    await wait(`document.querySelector(${JSON.stringify(surface(id) + ' [data-testid="prompt-input"]')})`, "세션 화면 준비");
    if (await evaluate(`!document.querySelector(${JSON.stringify(surface(id) + ' [data-testid="view-page"]')})`)) return;
    await wait(`document.querySelector(${JSON.stringify(surface(id) + ' [data-testid="open-current-workspace"]')})`, "현재 프로젝트 준비");
    await click(surface(id) + ' [data-testid="open-current-workspace"]');
    await wait(`document.querySelector(${JSON.stringify(surface(id) + ' [data-testid="target-dashboard"]')})`, "프로젝트 대시보드 진입");
    await click(surface(id) + ' [data-testid="chat-nav"]');
  };
  const sessions = async () => { const rows = await evaluate("window.www.listSessions()"); if (!Array.isArray(rows)) throw Error("세션 목록 없음"); return rows.map(obj); };
  const calls = async () => (await fs.readFile(path.join(evidence, "calls.jsonl"), "utf8")).trim().split("\n").map(line => obj(JSON.parse(line)));
  const screenshot = async (name: string) => { const value = obj(await command("Page.captureScreenshot", { format: "png" })); await fs.writeFile(path.join(evidence, name + ".png"), Buffer.from(String(value.data), "base64")); };
  await wait("document.querySelectorAll('[role=tab]').length===1", "최초 세션 탭 준비");
  const first = (await sessions())[0];
  const a = String(first?.id);
  await chat(a);
  await input(a, "session-A");
  await click(surface(a) + ' [data-testid="send-button"]');
  await wait(`window.www.listSessions().then(s=>s.find(x=>x.id===${JSON.stringify(a)})?.approvalCount===1)`, "A 승인과 실행 중");
  const firstSession = (await sessions()).find(item => item.id === a);
  const threadA = String(firstSession?.threadId);
  await pause(1800);
  await wait(`(()=>{const t=document.querySelector(${JSON.stringify(surface(a) + ' .transcript')});return t.scrollHeight>t.clientHeight})()`, "A 읽기 위치를 확인할 스크롤 영역");
  await evaluate(`(()=>{const t=document.querySelector(${JSON.stringify(surface(a) + ' .transcript')});t.scrollTop=0;t.dispatchEvent(new Event('scroll'))})()`);
  await click(surface(a) + ' [data-testid="detail-monitor-toggle"]');
  await input(a, "A 초안 보존");
  await click('[aria-label="새 대화 탭 추가"]');
  await wait("document.querySelectorAll('[role=tab]').length===2", "두 번째 독립 탭 생성");
  const second = (await sessions()).find(item => item.id !== a);
  const b = String(second?.id);
  if (obj(firstSession?.workspace).workspaceKey !== obj(second?.workspace).workspaceKey) throw Error("새 탭이 프로젝트를 복제하지 않았습니다.");
  await chat(b);
  const beforeOpen = await calls();
  const collision = String(await evaluate(`(async()=>{try{await window.www.openConversation(await window.www.workspace(${JSON.stringify(b)}),${JSON.stringify(threadA)});return 'allowed'}catch(e){return String(e)}})()`));
  if (collision === "allowed" || !collision.includes("다른 탭")) throw Error("다른 탭 소유 thread 열기 거부 실패: " + collision);
  const afterOpen = await calls();
  if (afterOpen.slice(beforeOpen.length).some(call => call.method === "thread/read" && obj(call.params).threadId === threadA)) throw Error("중복 thread/read가 Native에 전달됐습니다.");
  checks.push("B는 A 소유 thread를 IPC에서 거부하고 Native read 미호출");
  await input(b, "session-B");
  await click(surface(b) + ' [data-testid="send-button"]');
  await wait(`window.www.listSessions().then(s=>s.filter(x=>x.busy&&x.approvalCount===1).length===2)`, "두 세션 동시 실행·동일 ID 승인 대기");
  const live = await sessions();
  const threadB = String(live.find(item => item.id === b)?.threadId);
  if (!threadA || !threadB || threadA === threadB) throw Error("서로 다른 Native thread가 아닙니다.");
  const events = obj(await evaluate(`(async()=>{const a=await window.www.workspace(${JSON.stringify(a)}),b=await window.www.workspace(${JSON.stringify(b)});return {a:await window.www.events(a),b:await window.www.events(b)}})()`));
  const request = (key: string) => (Array.isArray(events[key]) ? events[key] as Data[] : []).find(event => event.kind === "request" && event.requestId === 42);
  const requestA = request("a");
  const requestB = request("b");
  if (!requestA?.approvalToken || !requestB?.approvalToken || requestA.approvalToken === requestB.approvalToken) throw Error("승인 토큰 격리 실패");
  const callsBeforeToken = await calls();
  const misuse = String(await evaluate(`(async()=>{try{await window.www.respond(await window.www.workspace(${JSON.stringify(b)}),42,'accept',${JSON.stringify(requestA.approvalToken)});return 'allowed'}catch(e){return String(e)}})()`));
  if (misuse === "allowed" || !misuse.includes("다른 대화 탭")) throw Error("다른 탭 토큰 거부 실패: " + misuse);
  if ((await calls()).slice(callsBeforeToken.length).some(row => !row.method && row.id === 42)) throw Error("오용 토큰이 Native에 전달됐습니다.");
  checks.push("같은 requestId 42의 서로 다른 토큰과 교차 오용 거부");
  await wait(`document.querySelector(${JSON.stringify(surface(a) + ' .command-card pre')})?.textContent.includes('session-A-tick-') && document.querySelector(${JSON.stringify(surface(b) + ' .command-card pre')})?.textContent.includes('session-B-tick-')`, "양쪽 Native 출력 스트리밍");
  const before = String(await evaluate(`document.querySelector(${JSON.stringify(surface(a) + ' .command-card pre')}).textContent`));
  await pause(500);
  const after = String(await evaluate(`document.querySelector(${JSON.stringify(surface(a) + ' .command-card pre')}).textContent`));
  if (before === after) throw Error("백그라운드 A 출력이 진행되지 않았습니다.");
  await select(a);
  await wait(`document.querySelector(${JSON.stringify(surface(a) + ' [data-testid="prompt-input"]')}).value==='A 초안 보존' && !document.querySelector(${JSON.stringify(surface(a) + ' [data-testid="activity-panel"]')}).hidden && document.querySelector(${JSON.stringify(surface(a) + ' .transcript')}).scrollTop<2`, "A 초안·읽기 위치·상세 패널 보존");
  await wait(`document.querySelector(${JSON.stringify(tab(a))}).parentElement.querySelector('.session-tab-close').disabled && document.querySelector(${JSON.stringify(tab(b))}).parentElement.querySelector('.session-tab-close').disabled`, "실행·승인 탭 닫기 UI 제한");
  const closeBusy = String(await evaluate(`window.www.closeSession(${JSON.stringify(a)}).then(()=> 'allowed',e=>String(e))`));
  if (closeBusy === "allowed") throw Error("실행 탭 직접 닫기가 허용됐습니다.");
  await click(surface(a) + ' .approval.open [data-decision="accept"]');
  await wait(`window.www.listSessions().then(s=>s.find(x=>x.id===${JSON.stringify(a)})?.approvalCount===0 && s.find(x=>x.id===${JSON.stringify(b)})?.approvalCount===1)`, "A 승인 후 B 승인 대기 유지");
  await click(surface(a) + ' [data-testid="interrupt-button"]');
  await wait(`window.www.listSessions().then(s=>!s.find(x=>x.id===${JSON.stringify(a)})?.busy && s.find(x=>x.id===${JSON.stringify(b)})?.busy)`, "A 중단 후 B 실행 유지");
  await wait(`document.querySelector(${JSON.stringify(tab(a))}).parentElement.querySelector('.session-tab-close').disabled`, "초안 있는 유휴 탭 닫기 UI 제한");
  await input(a, "");
  await wait(`!document.querySelector(${JSON.stringify(tab(a))}).parentElement.querySelector('.session-tab-close').disabled`, "초안 제거 후 닫기 가능");
  const allCalls = await calls();
  const pidA = Number(allCalls.find(row => row.method === "turn/start" && JSON.stringify(row.params).includes("session-A"))?.pid);
  const pidB = Number(allCalls.find(row => row.method === "turn/start" && JSON.stringify(row.params).includes("session-B"))?.pid);
  if (!pidA || !pidB || pidA === pidB) throw Error("별도 Native PID 근거가 없습니다.");
  await click(tab(a) + ' + .session-tab-close');
  await wait(`window.www.listSessions().then(s=>s.length===1&&s[0].id===${JSON.stringify(b)})`, "유휴 A 탭 제거와 B 보존");
  let exited = false;
  for (let i = 0; i < 100; i++) { try { process.kill(pidA, 0); } catch { exited = true; break; } await pause(50); }
  if (!exited) throw Error("닫은 A Native 프로세스가 살아 있습니다.");
  checks.push("유휴 탭 닫기 후 실제 자식 PID 종료");
  await select(b);
  await wait(`document.querySelector(${JSON.stringify(surface(b) + ' .approval.open')})`, "B 승인 요청 보존");
  await click(surface(b) + ' .approval.open [data-decision="accept"]');
  await click(surface(b) + ' [data-testid="interrupt-button"]');
  await wait(`window.www.listSessions().then(s=>s.length===1&&!s[0].busy)`, "B 종료");
  const lastClose = String(await evaluate(`window.www.closeSession(${JSON.stringify(b)}).then(()=> 'allowed',e=>String(e))`));
  if (lastClose === "allowed") throw Error("마지막 탭 직접 닫기가 허용됐습니다.");
  await wait(`document.querySelector(${JSON.stringify(tab(b))}).parentElement.querySelector('.session-tab-close').disabled`, "마지막 탭 UI 닫기 제한");
  await click('[aria-label="새 대화 탭 추가"]');
  await wait("document.querySelectorAll('[role=tab]').length===2", "프로젝트 격리용 탭 생성");
  const c = String((await sessions()).find(item => item.id !== b)?.id);
  const clone = (await sessions()).find(item => item.id === c);
  if (obj(clone?.workspace).workspaceKey !== obj(second?.workspace).workspaceKey) throw Error("신규 탭 프로젝트 복제 실패");
  await select(b);
  await input(b, "숨은 대화 초안");
  await click(surface(b) + ' [data-testid="new-conversation"]');
  await wait(`document.querySelector(${JSON.stringify(surface(b) + ' [data-testid="prompt-input"]')}).value==='' && document.querySelector(${JSON.stringify(tab(b))}).parentElement.querySelector('.session-tab-close').disabled`, "같은 탭의 숨은 대화 초안도 탭 닫기 차단");
  await wait(`document.querySelector(${JSON.stringify(surface(b) + ` [data-thread-id="${threadB}"]`)})`, "초안 보관 대화 목록");
  await click(surface(b) + ` [data-thread-id="${threadB}"]`);
  await wait(`document.querySelector(${JSON.stringify(surface(b) + ' [data-testid="prompt-input"]')}).value==='숨은 대화 초안'`, "숨은 대화 초안 복원");
  await input(b, "");
  await select(c);
  await click(surface(c) + ' [data-testid="view-page-nav"]');
  await wait(`document.querySelector(${JSON.stringify(surface(c) + ' [data-testid="open-www"]')})`, "WWW 프로젝트 선택 준비");
  await click(surface(c) + ' [data-testid="open-www"]');
  await wait(`window.www.workspace(${JSON.stringify(c)}).then(x=>x.path===${JSON.stringify(root)})`, "C 프로젝트 전환");
  const isolated = obj(await evaluate(`(async()=>({b:await window.www.workspace(${JSON.stringify(b)}),c:await window.www.workspace(${JSON.stringify(c)})}))()`));
  if (obj(isolated.b).path !== workspace || obj(isolated.c).path !== root) throw Error("다른 탭 프로젝트 격리 실패");
  checks.push("새 탭 프로젝트 복제 후 전환은 기존 탭에 영향 없음");
  await screenshot("sessions-final");
  const summary = { result: "passed", evidence, checks, threadA, threadB, pidA, pidB, coverage: "실제 Electron·IPC·별도 stdio 자식, 합성 Native fixture. 실제 모델·Windows·OS IME 미검증." };
  await fs.writeFile(path.join(evidence, "summary.json"), JSON.stringify(summary, null, 2));
  console.log(JSON.stringify(summary));
} catch (error) {
  await fs.writeFile(path.join(evidence, "partial-checks.json"), JSON.stringify(checks, null, 2));
  await fs.writeFile(path.join(evidence, "failure.txt"), String(error));
  console.error(String(error) + "\n증거: " + evidence);
  process.exitCode = 1;
} finally {
  socket?.close();
  child.kill("SIGTERM");
  await Promise.race([new Promise<void>(resolve => child.once("close", () => resolve())), pause(3000)]);
  if (child.exitCode === null) child.kill("SIGKILL");
  await stdout.close();
  await stderr.close();
}
